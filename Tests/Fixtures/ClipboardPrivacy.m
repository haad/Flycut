@interface FCRecordingOperator : FlycutOperator {
@public
    int mainThreadActions;
    int workerThreadActions;
}
@end

@implementation FCRecordingOperator
- (void)actionAfterListModification {
    @synchronized (self) {
        if ([NSThread isMainThread]) mainThreadActions++; else workerThreadActions++;
    }
    [super actionAfterListModification];
}
- (bool)saveFromStore:(FlycutStore *)store atIndex:(int)index withPrefix:(NSString *)prefix {
    fprintf(stderr, "FAIL: fixture reached the file-writing autosave path\n");
    abort();
}
@end

static NSString *const kSkipList = @"PasswordPboardType, org.nspasteboard.TransientType, org.nspasteboard.ConcealedType, org.nspasteboard.AutoGeneratedType";

static FCRecordingOperator *FreshOperator(void) {
    [[FCFakeDefaults standardUserDefaults] reset];
    FCFakeDefaults *defaults = [FCFakeDefaults standardUserDefaults];
    [defaults setObject:@0 forKey:@"savePreference"];
    [defaults setObject:@NO forKey:@"saveForgottenClippings"];
    [defaults setObject:@NO forKey:@"saveForgottenFavorites"];
    [defaults setObject:@YES forKey:@"skipPboardTypes"];
    [defaults setObject:kSkipList forKey:@"skipPboardTypesList"];
    [defaults setObject:@NO forKey:@"skipPasswordLengths"];
    FCRecordingOperator *op = [[FCRecordingOperator alloc] init];
    [op awakeFromNibDisplaying:10 withDisplayLength:40 withSaveSelector:NULL forTarget:nil];
    return op;
}

static int Check(BOOL condition, const char *message) {
    if (!condition) {
        fprintf(stderr, "FAIL: %s\n", message);
        return 1;
    }
    printf("PASS: %s\n", message);
    return 0;
}

static void DrainMainQueue(BOOL (^done)(void)) {
    NSDate *deadline = [NSDate dateWithTimeIntervalSinceNow:2.0];
    while (!done() && [deadline timeIntervalSinceNow] > 0)
        CFRunLoopRunInMode(kCFRunLoopDefaultMode, 0.02, true);
}

static int RunConcealed(void) {
    FCRecordingOperator *op = FreshOperator();
    [[FCFakeDefaults standardUserDefaults] setObject:@NO forKey:@"skipPasswordFields"];
    NSArray *concealed = @[NSPasteboardTypeString, @"org.nspasteboard.ConcealedType"];
    NSArray *plain = @[NSPasteboardTypeString];
    int failures = 0;
    failures += Check([op shouldSkip:@"fixture" ofType:NSPasteboardTypeString fromAvailableTypes:concealed],
                      "concealed marker is skipped with password heuristics off");
    failures += Check(![op shouldSkip:@"fixture" ofType:NSPasteboardTypeString fromAvailableTypes:plain],
                      "ordinary text is still captured with password heuristics off");
    [op release];
    return failures;
}

static int RunNoRevealNoSave(void) {
    FCRecordingOperator *op = FreshOperator();
    [[FCFakeDefaults standardUserDefaults] setObject:@YES forKey:@"skipPasswordFields"];
    [[FCFakeDefaults standardUserDefaults] setObject:@NO forKey:@"revealPasteboardTypes"];
    BOOL skipped = [op shouldSkip:@"fixture" ofType:NSPasteboardTypeString fromAvailableTypes:@[NSPasteboardTypeString]];
    int failures = 0;
    failures += Check(!skipped, "ordinary text is not skipped");
    failures += Check(op->mainThreadActions + op->workerThreadActions == 0,
                      "evaluating a clipping does not trigger a store save");
    failures += Check([op jcListCount] == 0, "evaluating a clipping does not modify the store");
    [op release];
    return failures;
}

static int RunRevealOnMain(void) {
    FCRecordingOperator *op = FreshOperator();
    [[FCFakeDefaults standardUserDefaults] setObject:@YES forKey:@"revealPasteboardTypes"];
    [op shouldSkip:@"" ofType:NSPasteboardTypeTIFF fromAvailableTypes:@[NSPasteboardTypeTIFF]];
    int failures = 0;
    failures += Check([op jcListCount] == 1 && [[op getClipFromCount:0] isEqualToString:NSPasteboardTypeTIFF],
                      "main-thread caller sees the revealed type immediately");
    failures += Check(op->mainThreadActions == 1 && op->workerThreadActions == 0,
                      "main-thread reveal runs the list-modification action once on the main thread");
    [op release];
    return failures;
}

static int RunRevealFromWorker(void) {
    FCRecordingOperator *op = FreshOperator();
    [[FCFakeDefaults standardUserDefaults] setObject:@YES forKey:@"revealPasteboardTypes"];
    __block int countOnWorker = -1;
    __block BOOL skipped = YES;
    dispatch_semaphore_t finished = dispatch_semaphore_create(0);
    dispatch_async(dispatch_get_global_queue(DISPATCH_QUEUE_PRIORITY_DEFAULT, 0), ^{
        skipped = [op shouldSkip:@"fixture" ofType:NSPasteboardTypeString fromAvailableTypes:@[NSPasteboardTypeString]];
        countOnWorker = [op jcListCount];
        dispatch_semaphore_signal(finished);
    });
    dispatch_semaphore_wait(finished, DISPATCH_TIME_FOREVER);
    dispatch_release(finished);
    int workerActions = op->workerThreadActions;
    DrainMainQueue(^BOOL { return [op jcListCount] == 1; });
    int failures = 0;
    failures += Check(!skipped, "reveal mode does not skip ordinary text");
    failures += Check(countOnWorker == 0, "capture worker does not insert into the store");
    failures += Check(workerActions == 0, "capture worker does not run the list-modification action");
    failures += Check([op jcListCount] == 1 && [[op getClipFromCount:0] isEqualToString:NSPasteboardTypeString],
                      "revealed type is committed on the main queue");
    failures += Check(op->mainThreadActions == 1, "list-modification action runs once on the main thread");
    [op release];
    return failures;
}

int main(int argc, const char *argv[]) {
    @autoreleasepool {
        if (argc != 2) return 2;
        if (strcmp(argv[1], "concealed") == 0) return RunConcealed();
        if (strcmp(argv[1], "no-reveal-no-save") == 0) return RunNoRevealNoSave();
        if (strcmp(argv[1], "reveal-main") == 0) return RunRevealOnMain();
        if (strcmp(argv[1], "reveal-worker") == 0) return RunRevealFromWorker();
    }
    return 3;
}
