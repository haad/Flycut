#!/usr/bin/env python3
"""Regression tests: content marked concealed/transient is never saved by default.

The fixture compiles the real FlycutOperator and engine sources, lets the real
-init register the shipped defaults, and asks the production
-shouldSkip:ofType:fromAvailableTypes: about clipboard type combinations. User
defaults live in memory; any access to the general pasteboard or to the on-disk
image store aborts the fixture. No app bundle is built, no NIB is loaded.
"""

from __future__ import annotations

import pathlib
import subprocess
import tempfile
import unittest


ROOT = pathlib.Path(__file__).resolve().parents[1]

FIXTURE = r'''
#import <Cocoa/Cocoa.h>
#import <objc/runtime.h>
#import <string.h>
#import "FlycutOperator.h"
#import "FlycutImageStore.h"

// ---- OS boundary: persistent preferences are replaced by an in-memory store ----
@interface FCMemoryDefaults : NSObject { NSMutableDictionary *_values; }
@end
@implementation FCMemoryDefaults
- (id)init { if ((self = [super init])) _values = [[NSMutableDictionary alloc] init]; return self; }
- (void)registerDefaults:(NSDictionary *)values {
    for (id key in values) if (_values[key] == nil) _values[key] = values[key];
}
- (id)objectForKey:(NSString *)key { return _values[key]; }
- (id)valueForKey:(NSString *)key { return _values[key]; }
- (NSString *)stringForKey:(NSString *)key { return _values[key]; }
- (NSDictionary *)dictionaryForKey:(NSString *)key { return _values[key]; }
- (NSArray *)arrayForKey:(NSString *)key { return _values[key]; }
- (NSInteger)integerForKey:(NSString *)key { return [_values[key] integerValue]; }
- (BOOL)boolForKey:(NSString *)key { return [_values[key] boolValue]; }
- (void)setObject:(id)value forKey:(NSString *)key {
    if (value) _values[key] = value; else [_values removeObjectForKey:key];
}
- (void)setValue:(id)value forKey:(NSString *)key { [self setObject:value forKey:key]; }
- (void)setBool:(BOOL)value forKey:(NSString *)key { [self setObject:@(value) forKey:key]; }
- (BOOL)synchronize { return YES; }
@end

static FCMemoryDefaults *memoryDefaults;
static id FCStandardDefaults(id object, SEL selector) { return memoryDefaults; }
static id FCForbidden(id object, SEL selector) {
    fprintf(stderr, "fixture touched a forbidden OS boundary: +[%s %s]\n",
            class_getName(object), sel_getName(selector));
    abort();
}

static NSString *const Concealed = @"org.nspasteboard.ConcealedType";
static NSString *const Transient = @"org.nspasteboard.TransientType";
static NSString *const AutoGenerated = @"org.nspasteboard.AutoGeneratedType";
static NSString *const LegacyPassword = @"PasswordPboardType";

int main(int argc, const char *argv[]) {
    @autoreleasepool {
        if (argc != 2) return 2;
        NSString *mode = [NSString stringWithUTF8String:argv[1]];
        method_setImplementation(class_getClassMethod([NSUserDefaults class], @selector(standardUserDefaults)),
                                 (IMP)FCStandardDefaults);
        method_setImplementation(class_getClassMethod([NSPasteboard class], @selector(generalPasteboard)),
                                 (IMP)FCForbidden);
        method_setImplementation(class_getClassMethod([FlycutImageStore class], @selector(sharedStore)),
                                 (IMP)FCForbidden);
        memoryDefaults = [[FCMemoryDefaults alloc] init];
        [memoryDefaults setObject:@0 forKey:@"savePreference"];

        // Each case: user overrides on top of the shipped defaults, the copy's types,
        // its text, and whether the clipping must be skipped.
        NSDictionary *cases = @{
            @"default-concealed":      @[@{}, @[NSPasteboardTypeString, Concealed], @"s3cret value", @YES],
            @"default-transient":      @[@{}, @[NSPasteboardTypeString, Transient], @"s3cret value", @YES],
            @"default-autogenerated":  @[@{}, @[NSPasteboardTypeString, AutoGenerated], @"s3cret value", @YES],
            @"default-password-type":  @[@{}, @[NSPasteboardTypeString, LegacyPassword], @"s3cret value", @YES],
            @"default-ordinary":       @[@{}, @[NSPasteboardTypeString], @"ordinary text", @NO],
            @"heuristics-off-concealed":
                @[@{@"skipPasswordFields": @NO}, @[NSPasteboardTypeString, Concealed], @"s3cret value", @YES],
            @"heuristics-off-password-type":
                @[@{@"skipPasswordFields": @NO}, @[NSPasteboardTypeString, LegacyPassword], @"s3cret value", @YES],
            @"heuristics-off-ordinary":
                @[@{@"skipPasswordFields": @NO, @"skipPasswordLengths": @YES},
                  @[NSPasteboardTypeString], @"Abcdefgh1!xy", @NO],
            @"heuristics-on-length-match":
                @[@{@"skipPasswordLengths": @YES}, @[NSPasteboardTypeString], @"Abcdefgh1!xy", @YES],
            @"concealed-opt-out-keeps-private-copy":
                @[@{@"skipConcealedTypes": @NO}, @[NSPasteboardTypeString, Concealed, Transient], @"private window text", @NO],
            @"concealed-opt-out-still-skips-password-type":
                @[@{@"skipConcealedTypes": @NO}, @[NSPasteboardTypeString, Concealed, LegacyPassword], @"s3cret value", @YES],
            @"type-filters-off":
                @[@{@"skipPboardTypes": @NO, @"skipConcealedTypes": @NO},
                  @[NSPasteboardTypeString, Concealed, LegacyPassword], @"s3cret value", @NO],
            @"pboard-types-off-still-skips-concealed":
                @[@{@"skipPboardTypes": @NO}, @[NSPasteboardTypeString, Concealed], @"s3cret value", @YES],
            @"concealed-opt-out-keeps-auto-generated":
                @[@{@"skipConcealedTypes": @NO}, @[NSPasteboardTypeString, AutoGenerated], @"generated text", @NO],
        };
        NSArray *spec = cases[mode];
        if (spec == nil) return 3;

        FlycutOperator *op = [[FlycutOperator alloc] init];   // registers the shipped defaults
        [op awakeFromNibDisplaying:10 withDisplayLength:40 withSaveSelector:NULL forTarget:nil];
        NSDictionary *overrides = spec[0];
        for (NSString *key in overrides) [memoryDefaults setObject:overrides[key] forKey:key];

        BOOL skipped = [op shouldSkip:spec[2] ofType:NSPasteboardTypeString fromAvailableTypes:spec[1]];
        BOOL expected = [spec[3] boolValue];
        printf("%s: skipped=%s expected=%s\n", argv[1], skipped ? "YES" : "NO", expected ? "YES" : "NO");
        return skipped == expected ? 0 : 10;
    }
}
'''

MODES = {
    "default-concealed": "concealed (password manager / private window) content was saved by default",
    "default-transient": "transient content was saved by default",
    "default-autogenerated": "auto-generated content was saved by default",
    "default-password-type": "legacy password-typed content was saved by default",
    "default-ordinary": "ordinary text was skipped",
    "heuristics-off-concealed": "turning off the password heuristics disabled the concealed-type filter",
    "heuristics-off-password-type": "turning off the password heuristics disabled the password-type filter",
    "heuristics-off-ordinary": "the length heuristic ran although password heuristics were off",
    "heuristics-on-length-match": "the length heuristic no longer skips a matching string",
    "concealed-opt-out-keeps-private-copy": "opting out of the concealed filter did not keep the clipping",
    "concealed-opt-out-still-skips-password-type": "the concealed opt-out also disabled the password-type filter",
    "type-filters-off": "content was skipped although both type filters were off",
    "pboard-types-off-still-skips-concealed": "turning off the password-type filter disabled the concealed-type filter",
    "concealed-opt-out-keeps-auto-generated": "opting out of the concealed filter did not keep auto-generated content",
}


def fixture_sources() -> list[pathlib.Path]:
    try:
        listed = subprocess.check_output(
            ["/usr/bin/git", "ls-files", "*.m"], cwd=ROOT, text=True, stderr=subprocess.DEVNULL
        ).splitlines()
    except (OSError, subprocess.CalledProcessError):
        listed = [str(path.relative_to(ROOT)) for path in ROOT.rglob("*.m")]
    return [
        ROOT / path
        for path in sorted(listed)
        if path != "main.m"
        and not path.startswith("FlycutHelper/")
        and not path.startswith("Tests/")
    ]


class ConcealedClipboardTypesRegressionTests(unittest.TestCase):
    binary: pathlib.Path
    directory: tempfile.TemporaryDirectory

    @classmethod
    def setUpClass(cls) -> None:
        cls.directory = tempfile.TemporaryDirectory(prefix="flycut-concealed-types-")
        temp = pathlib.Path(cls.directory.name)
        source = temp / "ConcealedTypesFixture.m"
        cls.binary = temp / "ConcealedTypesFixture"
        source.write_text(FIXTURE)
        sources = fixture_sources()
        command = [
            "/usr/bin/xcrun", "clang", "-fno-objc-arc", "-fobjc-weak", "-fblocks", "-fmodules",
            "-DFLYCUT_MAC=1", "-mmacosx-version-min=13.5", "-arch", "arm64",
            "-include", str(ROOT / "Flycut_Prefix.pch"),
        ]
        for include_dir in sorted({ROOT, *(path.parent for path in sources)}):
            command.extend(["-I", str(include_dir)])
        command.extend(str(path) for path in sources)
        command.append(str(source))
        for framework in ("Cocoa", "Carbon", "ServiceManagement", "CloudKit"):
            command.extend(["-framework", framework])
        command.extend(["-o", str(cls.binary)])
        cls.build = subprocess.run(
            command, cwd=ROOT, text=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=300
        )

    @classmethod
    def tearDownClass(cls) -> None:
        cls.directory.cleanup()

    def run_mode(self, mode: str) -> None:
        self.assertEqual(self.build.returncode, 0, self.build.stderr)
        run = subprocess.run(
            [str(self.binary), mode], cwd=ROOT, text=True,
            stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=60,
        )
        boundary = [line for line in run.stderr.splitlines() if "forbidden OS boundary" in line]
        self.assertEqual(
            run.returncode, 0,
            f"{MODES[mode]}; exit={run.returncode}; {run.stdout.strip()} {' '.join(boundary)}".strip(),
        )

    def test_concealed_content_is_skipped_by_default(self) -> None:
        self.run_mode("default-concealed")

    def test_transient_content_is_skipped_by_default(self) -> None:
        self.run_mode("default-transient")

    def test_auto_generated_content_is_skipped_by_default(self) -> None:
        self.run_mode("default-autogenerated")

    def test_password_typed_content_is_skipped_by_default(self) -> None:
        self.run_mode("default-password-type")

    def test_ordinary_text_is_kept_by_default(self) -> None:
        self.run_mode("default-ordinary")

    def test_concealed_filter_does_not_depend_on_password_heuristics(self) -> None:
        self.run_mode("heuristics-off-concealed")

    def test_password_type_filter_does_not_depend_on_password_heuristics(self) -> None:
        self.run_mode("heuristics-off-password-type")

    def test_length_heuristic_stays_behind_password_heuristics_switch(self) -> None:
        self.run_mode("heuristics-off-ordinary")

    def test_length_heuristic_still_skips_matching_strings(self) -> None:
        self.run_mode("heuristics-on-length-match")

    def test_concealed_opt_out_keeps_private_window_clippings(self) -> None:
        self.run_mode("concealed-opt-out-keeps-private-copy")

    def test_concealed_opt_out_keeps_password_type_filter(self) -> None:
        self.run_mode("concealed-opt-out-still-skips-password-type")

    def test_both_type_filters_off_keep_marked_content(self) -> None:
        self.run_mode("type-filters-off")

    def test_concealed_filter_does_not_depend_on_password_type_filter(self) -> None:
        self.run_mode("pboard-types-off-still-skips-concealed")

    def test_concealed_opt_out_keeps_auto_generated_content(self) -> None:
        self.run_mode("concealed-opt-out-keeps-auto-generated")

    def test_privacy_tooltips_use_spaced_en_dash(self) -> None:
        import xml.etree.ElementTree as ET
        xib = ET.parse(ROOT / "English.lproj" / "MainMenu.xib")
        tooltip = next((element.get("toolTip") or "") for element in xib.iter()
                       if "typical of generated passwords" in (element.get("toolTip") or ""))
        self.assertIn(" \u2013 typical of generated passwords", tooltip)
        texts = [value for element in xib.iter() for key, value in element.attrib.items()
                 if key in ("title", "toolTip", "placeholderString")]
        self.assertEqual([text for text in texts if "\u2014" in text], [])


if __name__ == "__main__":
    unittest.main()
