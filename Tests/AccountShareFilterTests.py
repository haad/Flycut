#!/usr/bin/env python3
"""Native tests for FlycutOperator's decision whether a clipping may be shared
with another account of this Mac (-mayShareClipping:ofType:fromAvailableTypes:).

Sharing applies Flycut's own password filters as if every one of them were
turned on, whatever the local settings say, plus a fixed list of pasteboard
types that never leave the account. Local capture (-shouldSkip:) stays as the
user set it. The fixture compiles the real FlycutOperator with in-memory
defaults; no pasteboard, file, app, network or real defaults domain is used.
"""
from __future__ import annotations

import os
import pathlib
import re
import subprocess
import tempfile
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "Tests/Fixtures/AccountShareFilter.m"
OPERATOR = ROOT / "FlycutOperator.m"
ENGINE = ROOT / "FlycutEngine/FlycutAccountShare.m"
CLANG = ["/usr/bin/xcrun", "clang", "-fno-objc-arc", "-fobjc-weak", "-fblocks", "-fmodules",
         "-mmacosx-version-min=13.5", "-arch", "arm64"]


def method_body(source: str, signature: str) -> str:
    start = source.index(signature + "\n{")
    depth = 0
    for index in range(source.index("{", start), len(source)):
        if source[index] == "{":
            depth += 1
        elif source[index] == "}":
            depth -= 1
            if depth == 0:
                return source[start:index + 1]
    raise AssertionError(f"Unclosed method: {signature}")


class AccountShareFilterTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.temporary = tempfile.TemporaryDirectory(prefix="flycut-share-filter-")
        cls.addClassCleanup(cls.temporary.cleanup)
        cls.artifacts = pathlib.Path(os.environ.get("FLYCUT_TEST_ARTIFACTS") or cls.temporary.name).resolve()
        cls.artifacts.mkdir(parents=True, exist_ok=True)
        cls.binary = cls.artifacts / "AccountShareFilter"
        command = CLANG + ["-I", str(ROOT), "-I", str(ROOT / "FlycutEngine"), str(FIXTURE),
                           "-framework", "Cocoa", "-o", str(cls.binary)]
        build = subprocess.run(command, cwd=ROOT, text=True, capture_output=True, timeout=300)
        (cls.artifacts / "build.log").write_text(build.stdout + build.stderr)
        if build.returncode:
            raise AssertionError(f"Native fixture compile failed ({build.returncode}):\n{build.stderr[-4000:]}")

    def run_case(self, mode: str) -> None:
        run = subprocess.run([str(self.binary), mode], cwd=ROOT, text=True, capture_output=True, timeout=60)
        output = run.stdout + run.stderr
        (self.artifacts / f"{mode}.log").write_text(output)
        print(output, end="")
        self.assertEqual(run.returncode, 0, output)
        self.assertIn("RESULT failures=0", output)

    def test_password_and_concealed_types_are_never_shared(self) -> None:
        self.run_case("forced-types")

    def test_length_and_character_check_always_applies_to_sharing(self) -> None:
        self.run_case("forced-length")

    def test_fixed_never_share_list(self) -> None:
        self.run_case("never-shared-types")

    def test_ordinary_copies_may_be_shared_and_settings_stay_untouched(self) -> None:
        self.run_case("ordinary")

    def test_local_capture_decision_is_unchanged(self) -> None:
        self.run_case("local-unchanged")

    def test_rules_are_not_duplicated(self) -> None:
        operator = OPERATOR.read_text()
        # The launch carry-over reads master's stored type list and names the marker master's
        # list held: master's past, not a factory value of this version.
        operator = operator.replace(method_body(operator, "+(void)carryOverConcealedTypesSetting"), "")
        operator = operator.replace(method_body(operator, "+(void)carryOverPasswordTypesSetting"), "")
        engine = ENGINE.read_text()
        # One length and character rule, used by both decisions.
        self.assertEqual(operator.count("uppercaseLetterCharacterSet"), 1)
        # Each factory type and length string is written once (registered and forced from it).
        for literal in ("PasswordPboardType", "com.agilebits.onepassword", "org.nspasteboard.ConcealedType",
                        "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "12, 20, 32"):
            self.assertEqual(operator.count(literal), 1, literal)
            self.assertFalse(literal in engine, f"{literal} is written in the engine too")
        share = method_body(operator, "-(BOOL)mayShareClipping:(NSString *)contents ofType:(NSString *)type "
                                      "fromAvailableTypes:(NSArray<NSString *> *)availableTypes")
        for token in ("setObject", "setBool", "revealPasteboardTypes"):
            self.assertFalse(token in share, f"-mayShareClipping: uses {token}")

    def test_engine_asks_the_operator_for_the_sharing_decision(self) -> None:
        engine = ENGINE.read_text()
        header = (ROOT / "FlycutEngine/FlycutAccountShare.h").read_text()
        self.assertTrue("-(BOOL)mayShareClipping:(NSString *)contents ofType:(NSString *)type "
                        "fromAvailableTypes:(NSArray<NSString *> *)availableTypes;" in header,
                        "the engine's filter protocol does not ask -mayShareClipping:")
        self.assertTrue("[filter mayShareClipping:text ofType:type fromAvailableTypes:availableTypes]" in engine,
                        "the engine does not ask its filter -mayShareClipping:")
        self.assertFalse("shouldSkip:" in engine, "the engine still asks -shouldSkip:")

    def test_fixture_links_no_real_defaults_or_pasteboard(self) -> None:
        symbols = subprocess.check_output(["/usr/bin/nm", "-u", str(self.binary)], text=True).split()
        for name in ("_OBJC_CLASS_$_NSUserDefaults", "_OBJC_CLASS_$_NSPasteboard",
                     "_NSSearchPathForDirectoriesInDomains"):
            self.assertNotIn(name, symbols)


if __name__ == "__main__":
    unittest.main()
