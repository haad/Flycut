// "Password types" (skipPboardTypes) no longer depends on skipPasswordFields either
// (see below). On master, whoever had skipPasswordFields stored off saved password
// managers' copies whatever skipPboardTypes said: the first launch sets
// skipPboardTypes = NO once for them, also if it was stored on. A stored
// skipPboardTypesList that still names the concealed, transient or auto-generated
// marker (master's factory list named all three) loses them once, if the concealed
// option is on after its own carry-over: it takes them over with the same effect, and
// turning it off then keeps those copies, as its tooltip says. With that option off
// the list stays as stored, so what master skipped through it is still skipped. Runs
// only right after the concealed carry-over, which reads master's list as it was.
// skipPboardTypesMigrationCompleted records that this check ran, whatever it decided.
+(void)carryOverPasswordTypesSetting
{
	NSUserDefaults *defaults = [NSUserDefaults standardUserDefaults];
	if ([defaults boolForKey:@"skipPboardTypesMigrationCompleted"])
		return;
	NSString *domain = [[NSBundle mainBundle] bundleIdentifier];
	NSDictionary *stored = domain != nil ? [defaults persistentDomainForName:domain] : nil;
	// Read as -boolForKey: does: a stored value that is no number or string is NO.
	id passwordFields = [stored objectForKey:@"skipPasswordFields"];
	if (passwordFields != nil && !([passwordFields respondsToSelector:@selector(boolValue)] && [passwordFields boolValue]))
		[defaults setBool:NO forKey:@"skipPboardTypes"];
	id list = [stored objectForKey:@"skipPboardTypesList"];
	if ([list isKindOfClass:[NSString class]] && [defaults boolForKey:@"skipConcealedTypes"]) {
		NSArray *markers = @[@"org.nspasteboard.ConcealedType", @"org.nspasteboard.TransientType",
		                     @"org.nspasteboard.AutoGeneratedType"];
		NSArray *items = [list componentsSeparatedByString:@","];
		NSMutableArray *kept = [NSMutableArray array];
		for (NSString *item in items)
			// Compared as -availableTypes:matchListForKey: reads the list: without spaces.
			if (![markers containsObject:[item stringByReplacingOccurrencesOfString:@" " withString:@""]])
				[kept addObject:item];
		if ([kept count] != [items count])
			[defaults setObject:[[kept componentsJoinedByString:@","] stringByTrimmingCharactersInSet:
				[NSCharacterSet whitespaceCharacterSet]] forKey:@"skipPboardTypesList"];
	}
	[defaults setBool:YES forKey:@"skipPboardTypesMigrationCompleted"];
}

// Before skipConcealedTypes existed, master's -shouldSkip: matched a copy's types
// against skipPboardTypesList only while skipPasswordFields and skipPboardTypes were
// both on, so whoever had turned either off, or had taken the concealed marker out
// of that list, kept concealed copies (Firefox private windows among them). The
// first launch of this version carries that over once: master's check off and
// skipConcealedTypes never stored -> skipConcealedTypes = NO. Master's values are
// the stored ones (read before the list may lose its markers, see above), else master's factory
// values (both switches on, the list naming the marker). "Stored" is the defaults'
// own persistent domain: -objectForKey: also answers from the registration domain
// (skipConcealedTypes is YES there, and skipPboardTypesList no longer names the
// marker) and launch arguments. skipConcealedTypesMigrationCompleted (named like
// sandboxMigrationCompleted) records that the check ran, whatever it decided, so
// changing those switches later never changes the concealed filter. The marker also
// tells an earlier build of this version ran here: its "Don't save passwords" no longer
// gated "Password types", so a stored skipPasswordFields = NO was chosen there and
// nothing is carried over, the types part included.
+(void)carryOverConcealedTypesSetting
{
	NSUserDefaults *defaults = [NSUserDefaults standardUserDefaults];
	if ([defaults boolForKey:@"skipConcealedTypesMigrationCompleted"])
		return;
	NSString *domain = [[NSBundle mainBundle] bundleIdentifier];
	NSDictionary *stored = domain != nil ? [defaults persistentDomainForName:domain] : nil;
	BOOL masterSkippedConcealed = YES;
	for (NSString *key in @[@"skipPasswordFields", @"skipPboardTypes"]) {
		// Read as -boolForKey: does: a stored value that is no number or string is NO.
		id value = [stored objectForKey:key];
		if (value != nil && !([value respondsToSelector:@selector(boolValue)] && [value boolValue]))
			masterSkippedConcealed = NO;
	}
	// Master read the list with -stringForKey: and dropped the spaces before splitting.
	id list = [stored objectForKey:@"skipPboardTypesList"];
	if (list != nil && !([list isKindOfClass:[NSString class]]
		&& [[[list stringByReplacingOccurrencesOfString:@" " withString:@""] componentsSeparatedByString:@","]
			containsObject:@"org.nspasteboard.ConcealedType"]))
		masterSkippedConcealed = NO;
	if (!masterSkippedConcealed && [stored objectForKey:@"skipConcealedTypes"] == nil)
		[defaults setBool:NO forKey:@"skipConcealedTypes"];
	[defaults setBool:YES forKey:@"skipConcealedTypesMigrationCompleted"];
	[self carryOverPasswordTypesSetting];
}

- (void)awakeFromNibDisplaying:(int) dispNum withDisplayLength:(int) dispLength withSaveSelector:(SEL) selector forTarget:(NSObject*) target
{
	displayNum = dispNum;
	displayLength = dispLength;
	saveSelector = selector;
	saveTarget = target;

	// Initialize the FlycutStore
	[self initializeStoresAndLoadContents];

	// Stack position starts @ 0 by default
	stackPosition = favoritesStackPosition = stashedStackPosition = 0;
}

-(FlycutStore*) allocInitFlycutStoreRemembering:(int) remembering
{
	return [[FlycutStore alloc] initRemembering:remembering
									 displaying:displayNum
							  withDisplayLength:displayLength];
}

-(void) initializeStores
{
	// Fixme - These stores are not released anywhere.
	if ( !clippingStore )
	{
		clippingStore = [self allocInitFlycutStoreRemembering:[[NSUserDefaults standardUserDefaults] integerForKey:@"rememberNum"]];
		clippingStore.deleteDelegate = self;
	}
	else
	{
		[clippingStore setDisplayNum:displayNum];
		[clippingStore setDisplayLen:displayLength];
	}

	if ( ! favoritesStore )
	{
		favoritesStore = [self allocInitFlycutStoreRemembering:[[NSUserDefaults standardUserDefaults] integerForKey:@"favoritesRememberNum"]];
		favoritesStore.deleteDelegate = self;
	}
	else
	{
		[favoritesStore setDisplayNum:displayNum];
		[favoritesStore setDisplayLen:displayLength];
	}

	stashedStore = NULL;
}

-(void) initializeStoresAndLoadContents
{
	[self initializeStores];

	// If our preferences indicate that we are saving, load the dictionary from the saved plist
	// and use it to get everything set up.
	if ( [[NSUserDefaults standardUserDefaults] integerForKey:@"savePreference"] >= 1 ) {
		[self loadEngineFromPList];
	}
}

-(void) willShowPreferences
