- (bool)saveFromStore:(FlycutStore*)store atIndex:(int)index withPrefix:(NSString*) prefix
{
    if ( [store jcListCount] > index ) {
        FlycutClipping *clipping = [store clippingAtPosition:index];
        BOOL isImage = [clipping isImageClipping];

        NSString *pbFullText = nil;
        NSData *imageData = nil;
        if (isImage) {
            imageData = [[FlycutImageStore sharedStore] imageDataForHash:[clipping imageHash]];
            if (!imageData) return NO;
        } else {
            pbFullText = [self clippingStringWithCount:index inStore:store];
            pbFullText = [pbFullText stringByReplacingOccurrencesOfString:@"\r" withString:@"\r\n"];
        }

        if (!dateFormatterForFilename) {
            // Date formatters are time-expensive to create, so create once and reuse.
            dateFormatterForFilename = [[NSDateFormatter alloc] init];
            [dateFormatterForFilename setDateFormat:@"yyyy-MM-dd 'at' HH.mm.ss"];
        }

        // Get the timestamp string:
        NSDate *currentDate = [NSDate date];
        NSString *dateString = [dateFormatterForFilename stringFromDate:currentDate];

        NSString *fileExt = isImage ? [FlycutImageStore fileExtensionForType:[clipping type]] : @"txt";
        NSString *fileName = [NSString stringWithFormat:@"%@%@Clipping %@.%@",
                              prefix, store == favoritesStore ? @"Favorite " : @"", dateString, fileExt];

        // Make a subdirectory, if doing autosave, to avoid a directory with too many files in it as that can make Finder effectively hang on launch if that directory were the desktop.
        NSString *subdirectoryString = nil;
        if ([prefix isEqualToString:@"Autosave "]) {
            if (!dateFormatterForDirectory) {
                // Date formatters are time-expensive to create, so create once and reuse.
                dateFormatterForDirectory = [[NSDateFormatter alloc] init];
                [dateFormatterForDirectory setDateFormat:@"'Autosave Clippings' yyyy/MM"];
            }
            subdirectoryString = [dateFormatterForDirectory stringFromDate:currentDate];
        }

        NSString *baseDirectoryString = nil;
        NSString *fileNameWithPath = nil;

#ifdef FLYCUT_MAC
        if ([prefix isEqualToString:@"Autosave "]) {
            NSURL* autoSaveToLocation = [[NSUserDefaults standardUserDefaults] URLForKey:@"autoSaveToLocation"];
            if (autoSaveToLocation) {
                baseDirectoryString = autoSaveToLocation.path;
            }
        } else {
            NSURL* saveToLocation = [[NSUserDefaults standardUserDefaults] URLForKey:@"saveToLocation"];
            if (saveToLocation) {
                baseDirectoryString = saveToLocation.path;
            }
        }
#endif

        if (!fileNameWithPath) {
            // An exact place to save wasn't set (like from a Save panel), so build one.

            if (!baseDirectoryString) {
                // Get the Desktop directory since nothing else was specified.
                NSArray *paths = NSSearchPathForDirectoriesInDomains
                (NSDesktopDirectory, NSUserDomainMask, YES);
                NSString *desktopDirectory = [paths objectAtIndex:0];

                baseDirectoryString = desktopDirectory;
            }

            if (subdirectoryString) {
                // Apply a subdirectory / subdirectories.
                NSString *directoryPath = [NSString stringWithFormat:@"%@/%@",
                                           baseDirectoryString, subdirectoryString];
                [[NSFileManager defaultManager] createDirectoryAtPath:directoryPath
                                          withIntermediateDirectories:YES
                                                           attributes:nil
                                                                error:nil];
                baseDirectoryString = directoryPath;
            }

            // Make a file name to write the data to using the base directory:
            fileNameWithPath = [NSString stringWithFormat:@"%@/%@",
                                baseDirectoryString, fileName];
        }

        if (isImage) {
            return [imageData writeToFile:fileNameWithPath atomically:YES];
        }
        return [pbFullText writeToFile:fileNameWithPath
                            atomically:NO
                              encoding:NSNonLossyASCIIStringEncoding
                                 error:nil];
    }
    return NO;
}

// A new favorite goes to the top of the favorites. The favorites keep the order the
// user gave them: with "Remove duplicates" a clipping equal to a favorite takes that
// favorite's place instead of the top (the store drops the equal one, as it does in
// the history), so there is no second copy. Without "Remove duplicates" a second
// copy goes on top, as before.
-(void)addClippingToFavorites:(FlycutClipping *)clipping
{
	int equal = [favoritesStore removeDuplicates] ? [favoritesStore indexOfClipping:clipping] : -1;
	[favoritesStore insertClipping:clipping atIndex:( equal >= 0 ) ? equal : 0];
}

- (bool)saveFromStackToFavorites
{
    if ( clippingStore != favoritesStore && [clippingStore jcListCount] > stackPosition ) {
        // Get text from clipping store.
        [self addClippingToFavorites:[clippingStore clippingAtPosition:stackPosition]];
        [self clearItemAtStackPosition];
        return YES;
    }
    return NO;
}

- (NSString*)getPasteFromIndex:(int) position {
	NSString *clipping = [self getClipFromCount:position];

	// "Move pasted item to top of stack" reorders the history only. The favorites keep
	// the order the user gave them however a favorite is pasted or copied, and the
	// selection stays on it.
	if ( clippingStore != favoritesStore
		&& [[NSUserDefaults standardUserDefaults] boolForKey:@"pasteMovesToTop"] ) {
		// Settle the stack position BEFORE moving, because the store redraws the bezel from
		// inside the move (delegateEndUpdates -> -[AppController endUpdates]).  Assigning
		// afterwards meant that redraw used the pre-move position, which then pointed at the
		// neighbour of the clipping being pasted - a visible flash of the wrong entry.
		// Once the clipping has been moved to the top, position 0 is that clipping.
		stackPosition = 0;
		[clippingStore clippingMoveToTop:position];

		[self actionAfterListModification];
	}
	return clipping;
}

-(NSString*)getClipFromCount:(int)indexInt
{
//    NSString *pbFullText;å
//    NSArray *pbTypes;
    if ( (indexInt + 1) > [clippingStore jcListCount] ) {
        // We're asking for a clipping that isn't there yet
		// This only tends to happen immediately on startup when not saving, as the entire list is empty.
        DLog(@"Out of bounds request to jcList ignored.");
        return nil;
    }
    return [self clippingStringWithCount:indexInt];
}

// Returns YES if any of the pasteboard's advertised types matches the comma-separated
// list of type identifiers stored under the given user-defaults key.
-(BOOL)availableTypes:(NSArray<NSString *> *)availableTypes matchListForKey:(NSString *)listKey
{
	NSSet *typesToSkip = [NSSet setWithArray: [[[[NSUserDefaults standardUserDefaults] stringForKey:listKey] stringByReplacingOccurrencesOfString:@" " withString:@""] componentsSeparatedByString: @","]];
	NSSet *pasteBoardTypes = [NSSet setWithArray: availableTypes];
	return [pasteBoardTypes intersectsSet: typesToSkip];
}

// The local capture decision (forced NO) and the one for sharing with another
// account (forced YES): forced counts every password filter as turned on and
// adds the factory lengths to the length list, so local settings can only make
// sharing stricter.
-(BOOL)shouldSkip:(NSString *)contents ofType:(NSString *)type fromAvailableTypes:(NSArray<NSString *> *)availableTypes forcingPasswordProtection:(BOOL)forced
{
	BOOL skipPasswordFields = forced || [[NSUserDefaults standardUserDefaults] boolForKey:@"skipPasswordFields"];

	// The diagnostics option is recorded by pollPB's main-thread commit path instead of
	// the content; evaluating a clipping never modifies the store.

	// The data-type filters apply on their own: turning off the password heuristics
	// below must not start saving content the source app marked as confidential.
	// Skip content the source app marks as a password (password managers, password fields).
	if ( availableTypes && ( forced || [[NSUserDefaults standardUserDefaults] boolForKey:@"skipPboardTypes"] )
		&& [self availableTypes:availableTypes matchListForKey:@"skipPboardTypesList"] )
		return YES;

	// Skip content the source app marks as concealed/transient/auto-generated. Password
	// managers use these markers too, so this is on by default. Firefox marks every copy
	// from a private window as concealed, so turning this off keeps those clippings.
	// Chromium-based browsers and Safari add no marker for private windows; they set a
	// pasteboard expiration date instead, which this check does not see.
	if ( availableTypes && ( forced || [[NSUserDefaults standardUserDefaults] boolForKey:@"skipConcealedTypes"] )
		&& [self availableTypes:availableTypes matchListForKey:@"skipConcealedTypesList"] )
		return YES;

	// Check to see if we are skipping passwords based on length and characters.
	if ( skipPasswordFields )
	{
		__block bool skipClipping = NO;

		// Check the array of lengths to skip for suspicious strings.
		if ( forced || [[NSUserDefaults standardUserDefaults] boolForKey:@"skipPasswordLengths"] )
		{
			int contentsLength = [contents length];
			NSString *lengths = [[NSUserDefaults standardUserDefaults] stringForKey:@"skipPasswordLengthsList"];
			if ( forced )
				lengths = [NSString stringWithFormat:@"%@,%@", lengths ?: @"", FlycutFactorySkipPasswordLengthsList];
			NSArray *lengthsArray = [[lengths stringByReplacingOccurrencesOfString:@" " withString:@""] componentsSeparatedByString: @","];
			[lengthsArray enumerateObjectsUsingBlock:^(id lengthString, NSUInteger idx, BOOL *stop)
			{
				if ( [lengthString integerValue] == contentsLength )
				{
					NSRange uppercaseLetter = [contents rangeOfCharacterFromSet: [NSCharacterSet uppercaseLetterCharacterSet]];
					NSRange lowercaseLetter = [contents rangeOfCharacterFromSet: [NSCharacterSet lowercaseLetterCharacterSet]];
					NSRange decimalDigit = [contents rangeOfCharacterFromSet: [NSCharacterSet decimalDigitCharacterSet]];
					NSRange punctuation = [contents rangeOfCharacterFromSet: [NSCharacterSet punctuationCharacterSet]];
					NSRange symbol = [contents rangeOfCharacterFromSet: [NSCharacterSet symbolCharacterSet]];
					NSRange control = [contents rangeOfCharacterFromSet: [NSCharacterSet controlCharacterSet]];
					NSRange illegal = [contents rangeOfCharacterFromSet: [NSCharacterSet illegalCharacterSet]];
					NSRange whitespaceAndNewline = [contents rangeOfCharacterFromSet: [NSCharacterSet whitespaceAndNewlineCharacterSet]];
					if ( NSNotFound == control.location
						&& NSNotFound == illegal.location
						&& NSNotFound == whitespaceAndNewline.location
						&& NSNotFound != uppercaseLetter.location
						&& NSNotFound != lowercaseLetter.location
						&& NSNotFound != decimalDigit.location
						&& ( NSNotFound != punctuation.location
							|| NSNotFound != symbol.location ) )
					{
						skipClipping = YES;
						*stop = YES;
					}
				}
			}];

			if (skipClipping)
				return YES;
		}
	}
	return NO;
}

-(BOOL)shouldSkip:(NSString *)contents ofType:(NSString *)type fromAvailableTypes:(NSArray<NSString *> *)availableTypes
{
	return [self shouldSkip:contents ofType:type fromAvailableTypes:availableTypes forcingPasswordProtection:NO];
}

+(NSArray<NSString *> *)neverSharedTypes
{
	NSMutableArray *types = [NSMutableArray array];
	for ( NSString *list in @[FlycutFactorySkipPboardTypesList, FlycutFactorySkipConcealedTypesList] )
		[types addObjectsFromArray:[list componentsSeparatedByString:@","]];
	// The other markers listed on nspasteboard.org.
	[types addObjectsFromArray:@[@"de.petermaurer.TransientPasteboardType", @"com.typeit4me.clipping",
								 @"Pasteboard generator type"]];
	return types;
}

-(BOOL)mayShareClipping:(NSString *)contents ofType:(NSString *)type fromAvailableTypes:(NSArray<NSString *> *)availableTypes
{
	if ( [contents length] == 0 || availableTypes == nil )
		return NO;
	if ( [[NSSet setWithArray:availableTypes] intersectsSet:[NSSet setWithArray:[FlycutOperator neverSharedTypes]]] )
		return NO;
	// A file copied in Finder: its name is no text the user copied, and the file cannot go along.
	if ( [availableTypes containsObject:@"public.file-url"] || [availableTypes containsObject:@"NSFilenamesPboardType"] )
		return NO;
	return ![self shouldSkip:contents ofType:type fromAvailableTypes:availableTypes forcingPasswordProtection:YES];
}

