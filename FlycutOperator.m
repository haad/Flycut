- (void)saveStore:(FlycutStore *)store toKey:(NSString *)key onDict:(NSMutableDictionary *)saveDict {
    NSMutableArray *jcListArray = [NSMutableArray array];
    for ( int i = 0 ; i < [store jcListCount] ; i++ )
    {
        FlycutClipping *clipping = [store clippingAtPosition:i];
        NSMutableDictionary *dict = [NSMutableDictionary dictionaryWithObjectsAndKeys:
                                     [clipping contents], @"Contents",
                                     [clipping type], @"Type",
                                     [NSNumber numberWithInt:i], @"Position",nil];

        if ([clipping isImageClipping]) {
            [dict setObject:[clipping imageHash] forKey:@"ImageHash"];
            [dict setObject:[NSNumber numberWithDouble:[clipping imageSize].width] forKey:@"ImageWidth"];
            [dict setObject:[NSNumber numberWithDouble:[clipping imageSize].height] forKey:@"ImageHeight"];
        }

        NSString *val = [clipping appLocalizedName];
        if ( nil != val )
            [dict setObject:val forKey:@"AppLocalizedName"];

        val = [clipping appBundleURL];
        if ( nil != val )
            [dict setObject:val forKey:@"AppBundleURL"];

        int timestamp = [clipping timestamp];
        if ( timestamp > 0 )
            [dict setObject:[NSNumber numberWithInt:timestamp] forKey:@"Timestamp"];

        NSDictionary *richData = [clipping richData];
        if ( nil != richData && [richData count] > 0 )
            [dict setObject:richData forKey:@"RichData"];

        [jcListArray addObject:dict];
    }
    [saveDict setObject:jcListArray forKey:key];
	[store clearModifiedSinceLastSaveStore];
}

// Saved history must be able to restore its images after a relaunch, including
// images captured while Save: Never kept them in memory only.
- (void)persistMemoryOnlyImagesOfStore:(FlycutStore *)store {
    for ( int i = 0 ; i < [store jcListCount] ; i++ )
    {
        FlycutClipping *clipping = [store clippingAtPosition:i];
        if ([clipping isImageClipping])
            [[FlycutImageStore sharedStore] persistMemoryOnlyImageForHash:[clipping imageHash]];
    }
}

-(void) saveEngine {
	// While the favorites store is swapped in, clippingStore IS favoritesStore and the main
	// store is held in stashedStore, so persist the main store from wherever it currently
	// is.  Saving clippingStore under "jcList" wrote the favorites list as the clipping
	// history and never wrote the real history at all - and with savePreference at "after
	// each change" that happens on the very next copy, no quit required.
	//
	// This relies on -switchToFavoritesStore / -restoreStashedStore keeping stashedStore
	// non-NULL exactly while clippingStore is favoritesStore.  A re-entrant
	// -switchToFavoritesStore would break that (it would stash the favorites store over the
	// main one), so keep that invariant in mind when touching either method.
	FlycutStore *mainStore = ( NULL != stashedStore ) ? stashedStore : clippingStore;

	// saveEngine saves to NSUserDefaults.  If there have been no modifications, just skip this to avoid busy activity for any observers.
	if ( !([mainStore modifiedSinceLastSaveStore]
		   || [favoritesStore modifiedSinceLastSaveStore]) )
		return;

    NSMutableDictionary *saveDict;
    saveDict = [NSMutableDictionary dictionaryWithCapacity:3];
    [saveDict setObject:@"0.8" forKey:@"version"];
    [saveDict setObject:[NSNumber numberWithInt:[[NSUserDefaults standardUserDefaults] integerForKey:@"rememberNum"]]
                 forKey:@"rememberNum"];
    [saveDict setObject:[NSNumber numberWithInt:[[NSUserDefaults standardUserDefaults] integerForKey:@"favoritesRememberNum"]]
                 forKey:@"favoritesRememberNum"];

	[saveTarget performSelector:saveSelector withObject:saveDict];

    // Persist the main store from wherever it currently is (see above), so its
    // memory-only images are written too while the favorites store is swapped in.
    [self persistMemoryOnlyImagesOfStore:mainStore];
    [self persistMemoryOnlyImagesOfStore:favoritesStore];
    [self saveStore:mainStore toKey:@"jcList" onDict:saveDict];
    [self saveStore:favoritesStore toKey:@"favoritesList" onDict:saveDict];

    [[NSUserDefaults standardUserDefaults] setObject:saveDict forKey:@"store"];
    [[NSUserDefaults standardUserDefaults] synchronize];
}

- (void)applicationWillTerminate {
	if ( [[NSUserDefaults standardUserDefaults] integerForKey:@"savePreference"] >= 1 ) {
		DLog(@"Saving on exit");
        [self saveEngine];
    } else {
        // Remove clips from store
        [[NSUserDefaults standardUserDefaults] setValue:[NSDictionary dictionary] forKey:@"store"];
        DLog(@"Saving preferences on exit");
        [[NSUserDefaults standardUserDefaults] synchronize];
        // Nothing refers to stored images any more; do not leave their contents on disk.
        [[FlycutImageStore sharedStore] removeAllImages];
    }
    [[FlycutImageStore sharedStore] removeEphemeralFiles];
}

